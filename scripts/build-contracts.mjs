// forge build + copy each contract's ABI and bytecode into
// packages/core/src/chain/abi/<Contract>.ts (typed `as const` for viem).
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { root, forgeBin } from './env.mjs';

const CONTRACTS = ['EthereumDIDRegistry', 'IssuerTrustRegistry', 'StatusListRegistry', 'VaultPointer'];
const contractsRoot = resolve(root, 'packages/contracts');
const abiDir = resolve(root, 'packages/core/src/chain/abi');

const build = spawnSync(forgeBin(), ['build', '--root', contractsRoot], { stdio: 'inherit' });
if (build.status !== 0) {
  console.error('forge build failed');
  process.exit(build.status ?? 1);
}

mkdirSync(abiDir, { recursive: true });
for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(resolve(contractsRoot, 'out', `${name}.sol`, `${name}.json`), 'utf8'));
  const ts =
    `// Generated by scripts/build-contracts.mjs from packages/contracts/out - do not edit.\n` +
    `export const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n` +
    `export const ${name}Bytecode = ${JSON.stringify(artifact.bytecode.object)} as const;\n`;
  writeFileSync(resolve(abiDir, `${name}.ts`), ts);
  console.log(`wrote ${name}.ts (${artifact.abi.length} ABI entries)`);
}
